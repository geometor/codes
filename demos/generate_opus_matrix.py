def main() -> None:
    """Validate and write `resources/opus_matrix.json`."""
    domain_ids = {d["id"] for d in DOMAINS}
    seen_ids: set[str] = set()
    for t in TOPICS:
        tid = str(t["id"])
        if tid in seen_ids:
            msg = f"Duplicate topic id: {tid}"
            raise ValueError(msg)
        seen_ids.add(tid)
        if t["domain_id"] not in domain_ids:
            msg = f"Unknown domain_id on {tid}: {t['domain_id']}"
            raise ValueError(msg)

    out_path = Path(__file__).resolve().parents[1] / "resources" / "opus_matrix.json"
    payload = {"domains": DOMAINS, "topics": TOPICS}
    out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(TOPICS)} canonical opus topics across {len(DOMAINS)} domains to {out_path}")


if __name__ == "__main__":
    main()
