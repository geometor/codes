def _row(
    topic_id: str,
    domain_id: str,
    title: str,
    role: str,
    cells: tuple[tuple[str, str], ...],
    notes: str,
) -> dict[str, object]:
    if len(cells) != len(BASE_SYSTEM_ORDER):
        msg = f"Topic {topic_id} has {len(cells)} cells; expected {len(BASE_SYSTEM_ORDER)}"
        raise ValueError(msg)
    if topic_id not in BYRNE_CELLS:
        msg = f"Topic {topic_id} missing from BYRNE_CELLS"
        raise ValueError(msg)
    cov: dict[str, dict[str, str]] = {}
    for sys_id, (st, ref) in zip(BASE_SYSTEM_ORDER[:-1], cells[:-1], strict=True):
        cov[sys_id] = {"status": st, "ref": ref}
    b_st, b_ref = BYRNE_CELLS[topic_id]
    cov["byrne_1847"] = {"status": b_st, "ref": b_ref}
    g_st, g_ref = cells[-1]
    cov["geometor_model"] = {"status": g_st, "ref": g_ref}
    return {
        "id": topic_id,
        "domain_id": domain_id,
        "title": title,
        "role": role,
        "coverage": cov,
        "notes": notes,
    }


