"""Truth foundations: the trust stack, truth ladder, bridges, and showcase data.

This module loads two curated data files:

* ``resources/foundations.toml`` — one record per system describing *how it knows*
  (ontology, language, assumptions, engine, certificate, checker, semantics), its
  rung on the Truth Ladder, the trusted components it depends on, and the bridges
  (translations / embeddings) between systems.
* ``resources/showcase.toml`` — a handful of theorems realized side by side across
  systems ("one theorem, many foundations").

Both files are the single source of truth for the cards, graphs, comparison table,
and the interactive Atlas widget generated by :mod:`geometor.codes.present`.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from geometor.codes.registry import default_resources_dir

LAYERS: tuple[tuple[str, str, str], ...] = (
    ("ontology", "Ontology", "What exists?"),
    ("language", "Language", "How is a statement written?"),
    ("assumptions", "Assumptions", "What is taken as given?"),
    ("engine", "Engine", "How are new truths derived?"),
    ("certificate", "Certificate", "What evidence is left behind?"),
    ("checker", "Checker", "What must be trusted?"),
    ("semantics", "Semantics", "What model makes it sound?"),
)
"""The seven layers of the Trust Stack: ``(key, label, question)``."""

AXES: tuple[tuple[str, str], ...] = (
    ("logic", "Logic / calculus"),
    ("exactness", "Exact vs numeric"),
    ("decidable", "Decision procedure"),
    ("diagram", "Role of the diagram"),
    ("degeneracy", "Degeneracy handling"),
    ("tcb_size", "Trusted base (size)"),
)
"""Comparison axes shown in the compact comparison table: ``(key, label)``."""


@dataclass(frozen=True)
class Level:
    """One rung of the Truth Ladder.

    Attributes:
        id: Level identifier (``L0`` … ``L5`` or ``H``).
        name: Short name (e.g. ``Instance``).
        claim: The strength of claim certified at this rung.
        color: Fill color used in graphs and widgets.
        rank: Sort order (low = weaker claim).
    """

    id: str
    name: str
    claim: str
    color: str
    rank: int


@dataclass(frozen=True)
class Trusted:
    """A trusted component (kernel, solver, engine, reader) systems depend on.

    Attributes:
        id: Component identifier.
        name: Display name.
        kind: Category (``kernel``, ``solver``, ``engine``, ``cas``, ``float``, ``human``).
        size: Approximate size or scale of the trusted code, as text.
        note: One-line note with evidence.
    """

    id: str
    name: str
    kind: str
    size: str = ""
    note: str = ""


@dataclass
class System:
    """One surveyed system and the full description of its truth foundation.

    Attributes:
        id: System identifier (matches ``context.toml`` where applicable).
        name: Display name.
        short: Compact label for graphs.
        ladder: Truth Ladder level id.
        archetype: Architectural family (``synthetic-formal``, ``rule-engine`` …).
        core: Whether the system is one of the core archetypes on the overview.
        summary: One-sentence answer to "why believe it?".
        upstream: Upstream URL.
        dossier: Docname of the long-form dossier page, if any.
        primitives: Primitive sorts / objects of the ontology.
        trusts: Ids of trusted components.
        stack: Trust Stack layer text keyed by layer key.
        axes: Comparison axis text keyed by axis key.
        example_lang: Pygments lexer for the example statement.
        example_code: A short real statement from the system's source.
        example_source: URL or path of the example.
        findings: Notable findings (audits, gaps) as short sentences.
        refs: Evidence references (``label``/``url`` dicts).
    """

    id: str
    name: str
    short: str
    ladder: str
    archetype: str
    core: bool = False
    summary: str = ""
    upstream: str = ""
    dossier: str = ""
    primitives: list[str] = field(default_factory=list)
    trusts: list[str] = field(default_factory=list)
    stack: dict[str, str] = field(default_factory=dict)
    axes: dict[str, str] = field(default_factory=dict)
    example_lang: str = "text"
    example_code: str = ""
    example_source: str = ""
    findings: list[str] = field(default_factory=list)
    refs: list[dict[str, str]] = field(default_factory=list)


@dataclass(frozen=True)
class Bridge:
    """A translation, embedding, or lineage edge between two systems.

    Attributes:
        source: Source system id.
        target: Target system id.
        kind: ``lineage``, ``embeds``, ``translates``, ``formalizes``, ``proves``, ``benchmark``.
        label: Short edge label.
        evidence: URL or citation backing the edge.
        status: ``realized``, ``partial``, or ``proposed``.
    """

    source: str
    target: str
    kind: str
    label: str
    evidence: str = ""
    status: str = "realized"


@dataclass(frozen=True)
class Lift:
    """A route by which a system's claims can climb the Truth Ladder.

    Attributes:
        system: System id.
        from_level: Current level id.
        to_level: Target level id.
        via: Mechanism (e.g. ``symbolic parameters``).
        status: ``realized``, ``partial``, or ``proposed``.
    """

    system: str
    from_level: str
    to_level: str
    via: str
    status: str = "proposed"


@dataclass
class Foundations:
    """All truth-foundation data loaded from ``foundations.toml``."""

    levels: list[Level]
    trusted: list[Trusted]
    systems: list[System]
    bridges: list[Bridge]
    lifts: list[Lift]
    thesis: str = ""

    def system(self, system_id: str) -> System | None:
        """Return the system with ``system_id`` or ``None``."""
        return next((s for s in self.systems if s.id == system_id), None)

    def level(self, level_id: str) -> Level | None:
        """Return the ladder level with ``level_id`` or ``None``."""
        return next((lv for lv in self.levels if lv.id == level_id), None)

    def trusted_component(self, trusted_id: str) -> Trusted | None:
        """Return the trusted component with ``trusted_id`` or ``None``."""
        return next((t for t in self.trusted if t.id == trusted_id), None)

    def systems_at(self, level_id: str) -> list[System]:
        """Return all systems placed on ladder level ``level_id``."""
        return [s for s in self.systems if s.ladder == level_id]

    def to_json(self) -> dict[str, Any]:
        """Serialize to a JSON-ready dict for the Atlas widget.

        Returns:
            Dict with ``layers``, ``axes``, ``levels``, ``trusted``, and ``systems``.
        """
        return {
            "layers": [{"key": k, "label": lb, "question": q} for k, lb, q in LAYERS],
            "axes": [{"key": k, "label": lb} for k, lb in AXES],
            "levels": [lv.__dict__ for lv in self.levels],
            "trusted": [t.__dict__ for t in self.trusted],
            "systems": [
                {
                    "id": s.id,
                    "name": s.name,
                    "short": s.short,
                    "ladder": s.ladder,
                    "archetype": s.archetype,
                    "core": s.core,
                    "summary": s.summary,
                    "trusts": s.trusts,
                    "stack": s.stack,
                    "axes": s.axes,
                    "example_lang": s.example_lang,
                    "example_code": s.example_code,
                    "card": f"foundations/cards/{s.id}",
                }
                for s in self.systems
            ],
        }


@dataclass(frozen=True)
class Realization:
    """One system's realization of a showcase theorem.

    Attributes:
        system: System id.
        ident: Identifier in that system (theorem / rule / builder name).
        status: ``theorem``, ``axiom``, ``rule``, ``witness``, ``generic``, ``gap``, ``absent``.
        lang: Pygments lexer for ``code``.
        code: Short real excerpt.
        source: URL or path of the excerpt.
        note: What certifies it (or why it is missing).
    """

    system: str
    ident: str
    status: str
    lang: str = "text"
    code: str = ""
    source: str = ""
    note: str = ""


@dataclass
class Showcase:
    """A theorem realized side by side across systems.

    Attributes:
        id: Slug (also the catalog principle id when ``principle`` is empty).
        title: Display title.
        euclid: Euclid reference (e.g. ``I.5``), if any.
        statement: Plain-language statement.
        why: Why this theorem stresses the foundations.
        principle: Catalog principle id.
        realizations: Per-system realizations.
    """

    id: str
    title: str
    euclid: str
    statement: str
    why: str
    principle: str
    realizations: list[Realization]


def _default_path(name: str) -> Path:
    return default_resources_dir() / name


def load_foundations(path: Path | None = None) -> Foundations:
    """Load ``foundations.toml``.

    Args:
        path: Optional explicit path; defaults to ``resources/foundations.toml``.

    Returns:
        Parsed :class:`Foundations`.
    """
    data = tomllib.loads((path or _default_path("foundations.toml")).read_text(encoding="utf-8"))
    levels = [
        Level(id=lid, rank=i, **{k: v for k, v in rec.items() if k in {"name", "claim", "color"}})
        for i, (lid, rec) in enumerate(data.get("levels", {}).items())
    ]
    trusted = [Trusted(id=tid, **rec) for tid, rec in data.get("trusted", {}).items()]
    systems: list[System] = []
    for sid, rec in data.get("systems", {}).items():
        example = rec.pop("example", {})
        systems.append(
            System(
                id=sid,
                example_lang=example.get("lang", "text"),
                example_code=example.get("code", "").rstrip(),
                example_source=example.get("source", ""),
                **rec,
            )
        )
    bridges = [Bridge(**b) for b in data.get("bridges", [])]
    lifts = [Lift(**lf) for lf in data.get("lifts", [])]
    return Foundations(
        levels=levels,
        trusted=trusted,
        systems=systems,
        bridges=bridges,
        lifts=lifts,
        thesis=data.get("meta", {}).get("thesis", ""),
    )


def load_showcase(path: Path | None = None) -> list[Showcase]:
    """Load ``showcase.toml``.

    Args:
        path: Optional explicit path; defaults to ``resources/showcase.toml``.

    Returns:
        Showcase theorems in file order.
    """
    data = tomllib.loads((path or _default_path("showcase.toml")).read_text(encoding="utf-8"))
    out: list[Showcase] = []
    for sid, rec in data.get("showcase", {}).items():
        reals = [
            Realization(**{**r, "code": r.get("code", "").rstrip()}) for r in rec.get("realizations", [])
        ]
        out.append(
            Showcase(
                id=sid,
                title=rec["title"],
                euclid=rec.get("euclid", ""),
                statement=rec.get("statement", ""),
                why=rec.get("why", ""),
                principle=rec.get("principle", sid),
                realizations=reals,
            )
        )
    return out


def audit_foundations(fnd: Foundations, showcase: list[Showcase] | None = None) -> list[str]:
    """Check referential integrity of the foundations and showcase data.

    Args:
        fnd: Loaded foundations.
        showcase: Optional loaded showcase theorems.

    Returns:
        Human-readable problems; empty when consistent.
    """
    problems: list[str] = []
    level_ids = {lv.id for lv in fnd.levels}
    trusted_ids = {t.id for t in fnd.trusted}
    system_ids = {s.id for s in fnd.systems}
    layer_keys = {k for k, _, _ in LAYERS}
    for s in fnd.systems:
        if s.ladder not in level_ids:
            problems.append(f"{s.id}: unknown ladder level {s.ladder!r}")
        problems.extend(f"{s.id}: unknown trusted component {t!r}" for t in s.trusts if t not in trusted_ids)
        missing = layer_keys - set(s.stack)
        if missing:
            problems.append(f"{s.id}: missing stack layers {sorted(missing)}")
    for b in fnd.bridges:
        for end in (b.source, b.target):
            if end not in system_ids:
                problems.append(f"bridge {b.source}->{b.target}: unknown system {end!r}")
    for lf in fnd.lifts:
        if lf.system not in system_ids:
            problems.append(f"lift: unknown system {lf.system!r}")
        for lv in (lf.from_level, lf.to_level):
            if lv not in level_ids:
                problems.append(f"lift {lf.system}: unknown level {lv!r}")
    for sc in showcase or []:
        problems.extend(
            f"showcase {sc.id}: unknown system {r.system!r}" for r in sc.realizations if r.system not in system_ids
        )
    return problems
